# ─── Сборка ───────────────────────────────────────────────────────────────────

_MARKER = re.compile(r"^\[a\d+\]\s*")
_LEADING_NUM = re.compile(r"^\d+(?:\.\d+)*\.?\s*")
# Пробел после номера подпункта, слипшегося с текстом («1.1.расходные» → «1.1. расходные»).
# Lookahead — только буква: иначе backtracking матчит «1.» в «1.1. текст».
_SUBNUM_GLUE = re.compile(r"^(\d+(?:\.\d+)*\.)(?=[^\s\d.])")
# Пробел после маркера списка «•слово» → «• слово».
_BULLET_GLUE = re.compile(r"^([•\-])(?=\S)")


def _clean(line: str) -> str:
    line = _MARKER.sub("", line.rstrip())
    line = _SUBNUM_GLUE.sub(r"\1 ", line)
    return _BULLET_GLUE.sub(r"\1 ", line)


def load_texts() -> dict[str, str]:
    """Собирает {код: дословный текст} из SPEC (по исходникам) и RAW."""
    files: dict[str, list[str]] = {}
    for name in ("ceo1", "ceo2"):
        path = SOURCE_DIR / f"{name}.txt"
        files[name] = path.read_text(encoding="utf-8").splitlines()

    texts: dict[str, str] = {}
    for code, spec in SPEC.items():
        src = files[spec["src"]]
        lines: list[str] = []
        for start, end in spec["lines"]:
            for i in range(start, end + 1):
                cleaned = _clean(src[i - 1])
                if cleaned:
                    lines.append(cleaned)
        # Номер пункта убираем только у первой строки записи.
        lines[0] = _LEADING_NUM.sub("", lines[0])
        text = "\n".join(lines)
        if spec.get("decap"):
            text = text[0].lower() + text[1:]
        if frame := spec.get("frame"):
            text = frame + text
        # Хвостовая запятая элемента списка → точка.
        text = text.rstrip()
        if text.endswith((",", ";")):
            text = text[:-1] + "."
        elif not text.endswith("."):
            text += "."
        texts[code] = text

    texts.update(RAW)
    return texts


