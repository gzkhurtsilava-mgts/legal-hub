/** Возвращает блок для маршрута по самому длинному совпавшему префиксу */
export function resolvePresentContent(pathname: string): PresentSection {
  let best: PresentSection = DEFAULT_SECTION;
  let bestLen = 0;
  for (const [prefix, section] of Object.entries(SECTIONS)) {
    const matches =
      prefix === "/"
        ? pathname === "/"
        : pathname === prefix || pathname.startsWith(prefix + "/");
    if (matches && prefix.length > bestLen) {
      best = section;
      bestLen = prefix.length;
    }
  }
  return best;
}
